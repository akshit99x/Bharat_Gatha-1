"""A quality report on the game's written content.

    npm run content:export && npm run content:report

Reads server/data/content.json and writes docs/CONTENT_REPORT.md: how many questions each region has, whether
the codex and the questions are written at a level a 12 to 16 year old can read, and any questions that look
wrong (duplicates, a correct answer that is much longer than the others, answers that give themselves away).
Nothing here changes the game: it tells you where to look.
"""

from __future__ import annotations

import argparse
import statistics
import sys
from collections import Counter
from pathlib import Path

from server.content import CONTENT_PATH, load_content
from server.readability import analyse

ROOT = Path(__file__).resolve().parent.parent
TARGET_GRADE = 10.0  # Flesch-Kincaid: the top of what a 14 to 15 year old reads comfortably


def codex_rows(content) -> list[dict]:
    rows = []
    for c in content.codex:
        text = " ".join(c["body"])
        a = analyse(text)
        rows.append({"id": c["id"], "zone": c["zoneId"], "title": c["title"], "words": a["words"], "grade": a["grade"], "sentence": a["avg_sentence"]})
    return rows


def question_rows(content) -> list[dict]:
    rows = []
    for q in content.questions:
        text = " ".join([q["stem"], q.get("context") or "", *q["options"], q["explain"]])
        a = analyse(text)
        rows.append({"id": q["id"], "zone": q["zoneId"], "grade": a["grade"], "words": a["words"]})
    return rows


def question_issues(content) -> list[str]:
    """Things worth a second look. Each is a prompt to read the question, not a verdict."""
    out: list[str] = []
    stems: dict[str, str] = {}
    for q in content.questions:
        norm = " ".join(q["stem"].lower().split())
        if norm in stems:
            out.append(f"`{q['id']}` has the same stem as `{stems[norm]}`.")
        stems[norm] = q["id"]
        opts = q["options"]
        if len({o.lower() for o in opts}) != len(opts):
            out.append(f"`{q['id']}` has two identical options.")
        if not 0 <= q["answer"] < len(opts):
            out.append(f"`{q['id']}`: the answer index is outside the options.")
            continue
        lens = [len(o) for o in opts]
        right = lens[q["answer"]]
        others = [n for i, n in enumerate(lens) if i != q["answer"]]
        # The classic giveaway: the correct option is the longest by a wide margin.
        if others and right > 1.8 * max(others) and right > 40:
            out.append(f"`{q['id']}`: the correct option is much longer than the others, which gives it away.")
        if len(opts) < 3:
            out.append(f"`{q['id']}` has only {len(opts)} options, so a guess is right half the time.")
        if q["explain"].strip().lower() == q["stem"].strip().lower():
            out.append(f"`{q['id']}`: the explanation just repeats the question.")
    return out


def length_bias(questions: list[dict]) -> dict:
    """How often the correct option is the longest one, against what guessing would give."""
    total = len(questions)
    longest = clear = 0
    for q in questions:
        lens = [len(o) for o in q["options"]]
        right = lens[q["answer"]]
        others = max((n for i, n in enumerate(lens) if i != q["answer"]), default=0)
        longest += right == max(lens)
        clear += right > 1.15 * others
    chance = sum(1 / len(q["options"]) for q in questions) / max(1, total)
    return {"total": total, "longest": longest, "clear": clear, "rate": longest / max(1, total), "chance": chance}


def _fmt(x) -> str:
    return "n/a" if x is None else f"{x:.1f}"


def build_report() -> str:
    c = load_content()
    cx, qs = codex_rows(c), question_rows(c)
    graded = [r["grade"] for r in cx if r["grade"] is not None]
    lines: list[str] = []
    w = lines.append
    w("# Content report")
    w("")
    w("Generated by `python -m tools.content_report` from `server/data/content.json`. It describes the game's written")
    w("content; it does not change it. Reading grade is the Flesch-Kincaid estimate (US school grade); the aim is")
    w(f"**{TARGET_GRADE:.0f} or below** for a 12 to 16 year old audience. It is a rough guide: it counts words and")
    w("syllables, and a name like *Mohenjo-daro* makes a plain sentence look harder than it is.")
    w("")
    w("## Summary")
    w("")
    w(f"- **{len(c.zones)}** regions, **{len(c.codex)}** codex entries, **{len(c.questions)}** authored questions, **{c.plaque_total}** plaques.")
    w(f"- Codex median reading grade **{statistics.median(graded):.1f}**; **{sum(1 for g in graded if g > TARGET_GRADE)}** of {len(graded)} entries are above {TARGET_GRADE:.0f}.")
    qg = [r["grade"] for r in qs if r["grade"] is not None]
    w(f"- Question median reading grade **{statistics.median(qg):.1f}**; **{sum(1 for g in qg if g > TARGET_GRADE)}** of {len(qg)} are above {TARGET_GRADE:.0f}.")
    bias = length_bias(c.questions)
    verdict = (
        "A student can do well by choosing the longest answer without knowing the history, so this is worth fixing."
        if bias["rate"] > bias["chance"] + 0.15 or bias["clear"]
        else "That is close to chance, so option length does not give the answer away."
    )
    w(f"- **Answer length:** the longest option is the correct one in **{bias['longest']}** of {bias['total']} questions ({bias['rate']:.0%}); pure chance would give about {bias['chance']:.0%}. In **{bias['clear']}** the correct option is clearly longer (by more than 15%) than every other. {verdict}")
    w("")
    w("## Questions by region")
    w("")
    w("| Region | Questions | Easy (1) | Medium (2) | Hard (3) | Median grade |")
    w("|---|---:|---:|---:|---:|---:|")
    by_zone = Counter(q["zoneId"] for q in c.questions)
    for z in c.zones:
        zq = [q for q in c.questions if q["zoneId"] == z["id"]]
        d = Counter(q["difficulty"] for q in zq)
        g = [r["grade"] for r in qs if r["zone"] == z["id"] and r["grade"] is not None]
        w(f"| {z['name']} | {by_zone[z['id']]} | {d[1]} | {d[2]} | {d[3]} | {_fmt(statistics.median(g)) if g else 'n/a'} |")
    general = [q for q in c.questions if q["zoneId"] not in c.zone_ids]
    if general:
        w(f"| (general) | {len(general)} | {sum(q['difficulty'] == 1 for q in general)} | {sum(q['difficulty'] == 2 for q in general)} | {sum(q['difficulty'] == 3 for q in general)} | |")
    thin = [z["name"] for z in c.zones if by_zone[z["id"]] < 12]
    w("")
    w("Regions with fewer than 12 authored questions lean on generated questions more: " + (", ".join(thin) if thin else "none.") )
    w("")
    w("## Skills the questions train")
    w("")
    w("| Skill | Questions |")
    w("|---|---:|")
    for skill, n in Counter(q["skill"] for q in c.questions).most_common():
        w(f"| {skill} | {n} |")
    w("")
    w("## Codex entries above the target reading grade")
    w("")
    hard = sorted((r for r in cx if r["grade"] is not None and r["grade"] > TARGET_GRADE), key=lambda r: -r["grade"])
    if hard:
        w("| Entry | Region | Grade | Words | Average sentence |")
        w("|---|---|---:|---:|---:|")
        for r in hard[:25]:
            w(f"| {r['title']} (`{r['id']}`) | {r['zone']} | {r['grade']:.1f} | {r['words']} | {r['sentence']:.0f} words |")
        if len(hard) > 25:
            w(f"| … and {len(hard) - 25} more | | | | |")
    else:
        w("None.")
    w("")
    w("## Questions worth a second look")
    w("")
    issues = question_issues(c)
    hardq = sorted((r for r in qs if r["grade"] is not None and r["grade"] > TARGET_GRADE + 2), key=lambda r: -r["grade"])[:10]
    if issues:
        w("\n".join(f"- {i}" for i in issues))
    else:
        w("No duplicates, giveaways or malformed questions found.")
    if hardq:
        w("")
        w("Hardest to read (grade more than two above the target): " + ", ".join(f"`{r['id']}` ({r['grade']:.0f})" for r in hardq) + ".")
    w("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(ROOT / "docs" / "CONTENT_REPORT.md"))
    ap.add_argument("--check", action="store_true", help="exit 1 if the question checks find anything (for CI)")
    args = ap.parse_args(argv)
    if not CONTENT_PATH.exists():
        print("Run `npm run content:export` first.", file=sys.stderr)
        return 2
    report = build_report()
    Path(args.out).write_text(report, encoding="utf-8")
    problems = question_issues(load_content())
    print(f"Wrote {args.out} ({len(problems)} question issue(s)).")
    return 1 if args.check and problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
